test('the second emit archives the first version and the cache offers it back', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const first = 'public class point {\n  public int x;\n  public void move(int dx) {}\n}\n'
    emitArtifacts({ cwd, source: 'demo.xl.md', target: 'csharp', files: [{ path: 'dist/csharp/Point.cs', content: first }], env: {} })
    const archived = read(cwd, 'dist/csharp/Point.cs')
    const second = 'public class point {\n  public int x;\n  public void move(int dx) { X += dx; }\n}\n'
    emitArtifacts({ cwd, source: 'demo.xl.md', target: 'csharp', files: [{ path: 'dist/csharp/Point.cs', content: second }], env: {} })
    // The archive keeps the artifact xl wrote, header included, not the raw input.
    assert.equal(read(cwd, 'dist/csharp/.xl/cache/demo.cs.1'), archived)
    assert.ok(read(cwd, 'dist/csharp/Point.cs').includes('X += dx'))
    const opened = contextFor({ cwd, source: 'demo.xl.md', target: 'csharp', env: {} })
    assert.equal(opened.context.previous.version, 1)
    assert.ok(opened.context.previous.text.includes('public void move(int dx) {}'))
  } finally {
    dropWorkspace(cwd)
  }
})

test('emit can skip verification when the caller asks', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const result = emitArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      options: { verify: false },
      files: [{ path: 'dist/csharp/Point.cs', content: 'public class point { }' }],
      env: {},
    })
    assert.equal(result.ok, true)
    assert.equal(existsSync(`${cwd}/dist/csharp/Point.cs`), true)
  } finally {
    dropWorkspace(cwd)
  }
})

test('a statement section is part of the contract and reaches the non-ts context', () => {
  const source = [
    '# namespace demo',
    'demo package.',
    '',
    '# class point',
    '',
    '## field x:int = 0',
    'x.',
    '',
    '# statement',
    'entry.',
    '```ts',
    'run();',
    '```',
    '',
    '## csharp',
    '```csharp',
    'Run();',
    '```',
    '',
  ].join('\n')
  const cwd = makeWorkspace({ 'demo.xl.md': source })
  try {
    const opened = contextFor({ cwd, source: 'demo.xl.md', target: 'csharp', env: {} })
    assert.deepEqual(opened.context.outputs.map(output => output.path), [
      'dist/csharp/DemoModule.cs',
      'dist/csharp/Point.cs',
    ])
    assert.deepEqual(opened.context.summary.statements, [{ index: 1, hasBody: true, sections: ['csharp'] }])
    assert.ok(opened.context.language.sections.some(
      section => section.owner === '# statement 1' && section.code === 'Run();',
    ))
    assert.match(opened.context.promptHash, /^[0-9a-f]{16}$/)
  } finally {
    dropWorkspace(cwd)
  }
})
