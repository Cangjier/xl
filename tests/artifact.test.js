test('emit writes the header, the fingerprint, the context hash, and the model', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const result = emitArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      model: 'deepseek-flash',
      files: [{ path: 'dist/csharp/Point.cs', content: 'public class point {\n  public int x;\n  public void move(int dx) {}\n}\n' }],
      env: {},
    })
    assert.equal(result.ok, true)
    assert.deepEqual(result.written, ['dist/csharp/Point.cs'])
    const artifact = read(cwd, 'dist/csharp/Point.cs')
    const lines = artifact.split('\n')
    assert.equal(lines[0], '// @generated by xl from demo.xl.md')
    assert.match(lines[1], /xl:sha256:[0-9a-f]{64} {2}xl:target:csharp {2}xl:ver:0\.1\.0 {2}xl:model:deepseek-flash {2}xl:prompt:[0-9a-f]{16}/)
    assert.equal(lines[3], '')
    assert.ok(artifact.endsWith('}\n'))
    assert.ok(existsSync(`${cwd}/dist/csharp/.xl/cache.json`))
  } finally {
    dropWorkspace(cwd)
  }
})

test('emit refuses a path that is not planned', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const result = emitArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      files: [{ path: 'elsewhere/Point.cs', content: 'public class point {}' }],
      env: {},
    })
    assert.equal(result.ok, false)
    assert.equal(result.written.length, 0)
    assert.ok(result.diagnostics.some(item => item.code === 'E2001'))
    assert.equal(existsSync(`${cwd}/elsewhere`), false)
  } finally {
    dropWorkspace(cwd)
  }
})

