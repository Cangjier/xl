const POINT_BODY = 'public class point {\n  public int x;\n  public void move(int dx) {}\n}\n'
const STALE_HEADER = [
  '// @generated by xl from stale.xl.md',
  '// xl:sha256:' + '0'.repeat(64) + '  xl:target:csharp  xl:ver:0.1.0',
  '// DO NOT EDIT - edit the .xl.md source and regenerate',
  '',
].join('\n')

test('stripArtifactHeader keeps the body and leaves ordinary text alone', () => {
  const body = stripArtifactHeader(`${STALE_HEADER}${POINT_BODY}`)
  assert.equal(body, POINT_BODY)
  assert.equal(stripArtifactHeader(POINT_BODY), POINT_BODY)
  // The blank line belongs to the header block and is not doubled into the body.
  assert.equal(body.startsWith('\n'), false)
})

test('emit accepts a product read from a headerless scratch file', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO, 'tmp/point.cs': POINT_BODY })
  try {
    const result = emitArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      files: [{ path: 'dist/csharp/Point.cs', from: 'tmp/point.cs' }],
      env: {},
    })
    assert.equal(result.ok, true)
    assert.deepEqual(result.written, ['dist/csharp/Point.cs'])
    assert.deepEqual(result.adopted, ['dist/csharp/Point.cs'])
    const lines = read(cwd, 'dist/csharp/Point.cs').split('\n')
    assert.equal(lines[0], '// @generated by xl from demo.xl.md')
    assert.match(lines[1], /xl:target:csharp/)
    assert.equal(lines[3], '')
    assert.deepEqual(lines.slice(4), POINT_BODY.split('\n'))
  } finally {
    dropWorkspace(cwd)
  }
})

test('emit strips an @generated header and re-renders it for this run', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO, 'tmp/point.cs': `${STALE_HEADER}${POINT_BODY}` })
  try {
    const first = emitArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      files: [{ path: 'dist/csharp/Point.cs', content: POINT_BODY }],
      env: {},
    })
    assert.equal(first.ok, true)

    // Write into the planned output path itself, the way an in-place edit does:
    // the header that is already there must not survive into the new product.
    writeFiles(cwd, { 'dist/csharp/Point.cs': `${STALE_HEADER}${POINT_BODY.replace('{}\n', '{ /* edited */ }\n')}` })
    const second = emitArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      files: [{ path: 'dist/csharp/Point.cs', from: 'dist/csharp/Point.cs' }],
      env: {},
    })
    assert.equal(second.ok, true)
    assert.deepEqual(second.adopted, ['dist/csharp/Point.cs'])
    const text = read(cwd, 'dist/csharp/Point.cs')
    assert.equal(text.match(/@generated by xl/g).length, 1)
    assert.equal(text.match(/DO NOT EDIT/g).length, 1)
    assert.ok(!text.includes('stale.xl.md'))
    assert.ok(text.includes('/* edited */'))
    assert.equal(parseArtifactHeader(text).sourcePath, 'demo.xl.md')
  } finally {
    dropWorkspace(cwd)
  }
})

