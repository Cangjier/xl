/**
 * Plan-channel tests: the generation context, structural verification, and the
 * artifact write with its header, archive, and cache record.
 *
 * @module xl/tests/artifact
 */

import assert from 'node:assert/strict'
import { existsSync } from 'node:fs'
import test from 'node:test'
import { contextFor, emitArtifacts, verifyArtifacts } from '../src/core/artifact.js'
import { dropWorkspace, makeWorkspace, read } from './helpers.js'

const DEMO = [
  '# namespace demo',
  'demo package.',
  '',
  '# class point',
  '',
  '## field x:int = 0',
  'x.',
  '',
  '## method move:(dx:int)=>void',
  'move.',
  '```ts',
  'this.x = dx;',
  '```',
  '',
  '### csharp',
  '```csharp',
  'public void Move(int dx) { X += dx; }',
  '```',
  '',
].join('\n')

test('the generation context reports outputs, contract, and language sections', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const opened = contextFor({ cwd, source: 'demo.xl.md', target: 'csharp', env: {} })
    assert.deepEqual(opened.context.outputs.map(output => output.path), [
      'dist/csharp/Point.cs',
    ])
    assert.equal(opened.context.channel, 'harness')
    assert.equal(opened.context.summary.types[0].name, 'point')
    assert.equal(opened.context.summary.types[0].members[1].name, 'move')
    assert.equal(opened.context.language.namespace.name, 'demo')
    assert.ok(opened.context.language.sections.some(section => section.code.includes('Move')))
    assert.match(opened.context.promptHash, /^[0-9a-f]{16}$/)
    assert.equal(opened.context.previous, null)
  } finally {
    dropWorkspace(cwd)
  }
})

test('the context hash changes when the source structure changes', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const first = contextFor({ cwd, source: 'demo.xl.md', target: 'csharp', env: {} }).context.promptHash
    const changed = DEMO.replace('## field x:int = 0', '## field x:int = 1')
    const cwd2 = makeWorkspace({ 'demo.xl.md': changed })
    const second = contextFor({ cwd: cwd2, source: 'demo.xl.md', target: 'csharp', env: {} }).context.promptHash
    assert.notEqual(first, second)
    dropWorkspace(cwd2)
  } finally {
    dropWorkspace(cwd)
  }
})

test('verification passes for content that matches the contract', () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const verdict = verifyArtifacts({
      cwd,
      source: 'demo.xl.md',
      target: 'csharp',
      files: [{ path: 'dist/csharp/Point.cs', content: 'public class point { public int x; public void move(int dx) {} }' }],
      env: {},
    })
    assert.equal(verdict.ok, true)
    assert.deepEqual(verdict.planned, ['dist/csharp/Point.cs'])
  } finally {
    dropWorkspace(cwd)
  }
})

