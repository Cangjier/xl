const DEMO = [
  '# class point',
  '',
  '## field x:int = 0',
  'x.',
  '',
].join('\n')

test('the application row declares what it needs', () => {
  assert.equal(name, 'xl-cli')
  assert.deepEqual(inject, ['cmdlineArgs', 'xl'])
})

test('parseArgs separates the command, the paths, and the options', () => {
  const parsed = parseArgs(['build', 'src', '--target', 'ts', '-t', 'csharp', '-o', 'dist', '--flat', 'pkg'])
  assert.equal(parsed.command, 'build')
  assert.deepEqual(parsed.paths, ['src', 'pkg'])
  assert.deepEqual(parsed.options.targets, ['ts', 'csharp'])
  assert.equal(parsed.options.out, 'dist')
  assert.equal(parsed.options.flat, true)
  assert.deepEqual(parsed.errors, [])
})

test('parseArgs accepts --name=value and short flags', () => {
  const parsed = parseArgs(['check', '--format=compact', '-q', '--ignore', 'W3011,W3012'])
  assert.equal(parsed.command, 'check')
  assert.equal(parsed.options.format, 'compact')
  assert.equal(parsed.options.quiet, true)
  assert.deepEqual(parsed.options.ignore, ['W3011', 'W3012'])
})

test('parseArgs stops option scanning at --', () => {
  const parsed = parseArgs(['build', '--', '--flat'])
  assert.deepEqual(parsed.paths, ['--flat'])
  assert.equal(parsed.options.flat, undefined)
})

test('parseArgs reports an unknown command, option, and missing value', () => {
  assert.equal(parseArgs(['deploy']).errors[0], 'unknown command "deploy"')
  assert.ok(parseArgs(['build', '--nope']).errors.some(message => message.includes('--nope')))
  assert.ok(parseArgs(['build', '--out']).errors.some(message => message.includes('requires a value')))
})

test('parseArgs rejects a value on a boolean flag', () => {
  assert.ok(parseArgs(['build', '--flat=yes']).errors.some(message => message.includes('takes no value')))
})

test('parseArgs rejects a non-numeric numeric option', () => {
  assert.ok(parseArgs(['build', '--concurrency', 'many']).errors.some(message => message.includes('requires a number')))
})

test('validateOptions rejects a closed value outside its set', () => {
  assert.equal(validateOptions({ naming: 'idiomatic' }).length, 0)
  assert.equal(validateOptions({ naming: 'kebab' }).length, 1)
  assert.equal(validateOptions({ format: 'xml' }).length, 1)
  assert.equal(validateOptions({ color: 'rainbow' }).length, 1)
})

test('--layout is no longer an option', () => {
  assert.ok(parseArgs(['build', '--layout', 'file']).errors.some(message => message.includes('--layout')))
})

/**
 * Run the CLI row against a fake context.
 * @param {readonly string[]} argv - the invocation's inner arguments.
 * @param {string} cwd - workspace root.
 * @returns {Promise<{code: number, stdout: string, stderr: string}>} the run outcome.
 */
async function runCli(argv, cwd) {
  const stdout = []
  const stderr = []
  const previous = { stdout: internals.stdout, stderr: internals.stderr }
  internals.stdout = { write: chunk => stdout.push(chunk) }
  internals.stderr = { write: chunk => stderr.push(chunk) }
  let resolveExit
  const exited = new Promise((resolve) => { resolveExit = resolve })
  const services = new Map([
    ['xl', createXlService({ workspaceRoot: cwd })],
    ['cmdlineArgs', { get: () => argv }],
    ['appExit', code => resolveExit(code)],
  ])
  const ctx = { get: serviceName => services.get(serviceName) }
  try {
    apply(ctx)
    const code = await exited
    return { code, stdout: stdout.join(''), stderr: stderr.join('') }
  } finally {
    internals.stdout = previous.stdout
    internals.stderr = previous.stderr
  }
}

test('xl build -t ts writes the artifact and exits 0', async () => {
  const cwd = makeWorkspace({ 'demo.xl.md': DEMO })
  try {
    const result = await runCli(['build', '-t', 'ts'], cwd)
    assert.equal(result.code, 0)
    assert.ok(read(cwd, 'dist/ts/demo.ts').startsWith('// @generated by xl'))
    assert.ok(result.stdout.includes('build done'))
  } finally {
    dropWorkspace(cwd)
  }
})

test('xl build -t ts runs a # statement after the declarations, unexported', async () => {
  const source = [
    '# method Main:(args:Array<string>)=>void',
    '入口。',
    '```ts',
    'console.log(args);',
    '```',
    '',
    '# statement',
    '进程入口：模块被 import 时执行一次。',
    '```ts',
    'Main(process.argv.slice(2));',
    '```',
    '',
  ].join('\n')
  const cwd = makeWorkspace({ 'demo.xl.md': source })
  try {
    const result = await runCli(['build', '-t', 'ts'], cwd)
    assert.equal(result.code, 0)
    const artifact = read(cwd, 'dist/ts/demo.ts')
    assert.ok(artifact.startsWith('// @generated by xl'))
    assert.ok(artifact.includes('export function Main(args: string[]): void {'))
    // The statement is the last segment, carries no export, and keeps its prose out.
    assert.ok(artifact.endsWith('Main(process.argv.slice(2));\n'))
    assert.ok(!artifact.includes('export Main(process.argv'))
    assert.ok(!artifact.includes('进程入口'))
  } finally {
    dropWorkspace(cwd)
  }
})

