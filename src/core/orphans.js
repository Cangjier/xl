/**
 * Residue detection: outputs whose `*.xl.md` source no longer exists.
 *
 * The incremental cache is keyed by source, so deleting a source is invisible
 * to every other xl operation: the next run simply plans nothing for it and the
 * products it wrote keep sitting in the output tree, where the language
 * toolchain (and a publish step) still picks them up. This module is the one
 * place that asks the opposite question — *which products no longer have a
 * source* — and it answers it from the filesystem rather than from any single
 * run's input list, because the deleted source is exactly what a run no longer
 * sees.
 *
 * Two independent channels, deliberately redundant:
 *
 * 1. **The artifact header.** Every product xl wrote carries
 *    `@generated by xl from <source>` (xl-cli §3.6). Walking `<out>` finds a
 *    product whose recorded source does not exist, whatever happened to the
 *    cache, whatever the current `-t` list is, and whoever deleted the source.
 *    This is the primary channel: it is self-describing, so it needs no index.
 * 2. **The per-language cache.** `<out>/<lang>/.xl/cache.json` records the
 *    products of every source × target, including ones whose product was itself
 *    removed. A record whose source is gone is reported as residue too — the
 *    product may be back (restored from a branch), or the cache entry is what
 *    tells the story.
 *
 * Nothing here decides anything by name or by configuration: a cache document
 * is recognized by its own shape, and an artifact by its own first line.
 *
 * @module xl/core/orphans
 */

import { readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { isAbsolute, join, resolve } from 'node:path'
import { diag } from './diagnostics.js'
import { parseArtifactHeader } from './header.js'
import { resolveOutput } from './plan.js'
import { HEADER_MARK, toPosix } from './text.js'

/** How deep under the output root the walk looks. Language directory + source hierarchy. */
export const DEFAULT_SCAN_DEPTH = 8

/** Bytes read from each file: enough for the three header lines, and no more. */
const HEAD_BYTES = 8192

/** Cache document name, wherever a cache directory happens to be called. */
const CACHE_FILE = 'cache.json'

/** Separator between the source and target halves of a cache key (cache.js). */
const KEY_SEPARATOR = '\u0000'

/**
 * @typedef {object} Orphan
 * @property {string} out - the produced path, POSIX, relative to the working directory.
 * @property {string | null} source - the deleted source the product names, when known.
 * @property {string | null} target - the target language, when known.
 * @property {'header' | 'cache'} found - which channel reported it.
 * @property {boolean} exists - whether the produced file is still on disk.
 * @property {string} reason - one sentence for a human reader.
 */

/**
 * Every output under a root whose source is gone.
 *
 * The result is sorted by produced path, so the same tree always yields the same
 * report. Nothing is written and nothing is deleted.
 * @param {object} input - the scan input.
 * @param {string} input.cwd - working directory that recorded paths resolve against.
 * @param {string} input.out - output root, absolute or relative to `cwd`.
 * @param {number} [input.depth] - how deep under the output root to look.
 * @returns {Orphan[]} the residue, in stable order.
 */
export function findOrphans({ cwd, out, depth = DEFAULT_SCAN_DEPTH }) {
  const root = resolveOutput(cwd, out)
  const records = []
  walkOutputs({ root, cwd, depth, records })
  walkCaches({ root, cwd, depth, records })
  return finalize(records)
}

/**
 * Turn residue into the diagnostics of a run (`E2004`).
 *
 * The diagnostic is reported against the *product*, not against the source: the
 * source is the thing that is missing, so there is no file to point a caret at.
 * `E2004` is a warning by the code table, exactly like the other artifact-layer
 * problem that is the author's to fix (`E2003`, a hand-edited product), and one
 * `--ignore E2004` silences it.
 * @param {readonly Orphan[]} orphans - the residue.
 * @returns {object[]} diagnostics, in the order the residue was reported.
 */
export function orphanDiagnostics(orphans) {
  return orphans.map(orphan => diag({
    code: 'E2004',
    file: orphan.out,
    line: 1,
    msg: orphan.reason,
    help: helpOf(orphan),
  }))
}

/**
 * Delete the given residue, and with it the claim the cache still makes on it.
 *
 * Removal is per file and best-effort:
 *
 * * a product that no longer carries an xl header is refused and named, because
 *   xl never deletes a file it cannot prove it wrote (xl-cli §3.5);
 * * a record whose product is already gone has nothing to delete, so it is
 *   reported as `skipped` rather than treated as a failure;
 * * a cache entry for one of *these* sources is dropped, so a second run does
 *   not report the same residue again. This is what makes the operation
 *   idempotent. The scope is deliberate: pruning residue of source A never
 *   touches the cache record of source B, even when B is missing too.
 *
 * A directory left empty behind a removed product is left in place, and no
 * cache document is touched unless it actually held such an entry.
 * @param {object} input - the removal input.
 * @param {string} input.cwd - working directory.
 * @param {string} input.out - output root, absolute or relative to `cwd`.
 * @param {readonly Orphan[]} input.orphans - the residue to remove.
 * @returns {{removed: string[], refused: string[], skipped: string[], dropped: string[]}} the outcome.
 */
export function removeOrphans({ cwd, out, orphans }) {
  const removed = []
  const refused = []
  const skipped = []
  const sources = new Set()
  for (const orphan of orphans) {
    if (typeof orphan.source === 'string' && orphan.source !== '') sources.add(orphan.source)
    const absolute = resolveOutput(cwd, orphan.out)
    if (!statOf(absolute)?.isFile()) {
      skipped.push(orphan.out)
      continue
    }
    if (!isArtifactFile(absolute)) {
      refused.push(orphan.out)
      continue
    }
    try {
      rmSync(absolute)
      removed.push(orphan.out)
    } catch {
      refused.push(orphan.out)
    }
  }
  const dropped = forgetStaleCacheEntries({ cwd, out, sources: [...sources] })
  return { removed, refused, skipped, dropped }
}

/**
 * Drop the cache entries that name one of the given sources.
 *
 * The cache is an optimization, so a record for a source that is gone can only
 * ever mislead: it reports a product as current that xl cannot plan any more.
 * Only the listed sources are affected — a live record is never touched, and a
 * document with nothing to drop is not rewritten.
 * @param {object} input - the request.
 * @param {string} input.cwd - working directory.
 * @param {string} input.out - output root.
 * @param {readonly string[]} [input.sources] - the sources to forget; omitted
 *   means every source under the output root that no longer exists.
 * @returns {string[]} the sources dropped, sorted and deduplicated.
 */
export function forgetStaleCacheEntries({ cwd, out, sources }) {
  const root = resolveOutput(cwd, out)
  const wanted = sources === undefined ? null : new Set(sources)
  /** @type {Set<string>} */
  const dropped = new Set()
  for (const file of cacheFiles({ root, depth: DEFAULT_SCAN_DEPTH })) {
    let parsed
    try {
      parsed = JSON.parse(readFileSync(file, 'utf8'))
    } catch {
      continue
    }
    const entries = parsed?.entries
    if (entries === null || typeof entries !== 'object') continue
    let changed = false
    for (const [key, value] of Object.entries(entries)) {
      const separator = key.indexOf(KEY_SEPARATOR)
      if (separator <= 0) continue
      const src = key.slice(0, separator)
      if (wanted === null ? sourceExists(cwd, src) : !wanted.has(src)) continue
      if (!Array.isArray(value?.out) || value.out.length === 0) continue
      delete entries[key]
      dropped.add(src)
      changed = true
    }
    if (!changed) continue
    try {
      writeFileSync(file, `${JSON.stringify(parsed, null, 2)}\n`, 'utf8')
    } catch {
      // A cache that cannot be rewritten is left as it is: the products the
      // caller asked to delete are gone, and the cache is best-effort (cache.js).
    }
  }
  return [...dropped].sort(compare)
}

/**
 * Every cache document under the output root, at any depth the scan reaches.
 * @param {object} input - the walk input.
 * @param {string} input.root - absolute directory.
 * @param {number} input.depth - remaining depth.
 * @returns {string[]} absolute paths of the cache documents found.
 */
function cacheFiles({ root, depth }) {
  const found = []
  for (const entry of readEntries(root)) {
    const absolute = join(root, entry.name)
    if (entry.isDirectory()) {
      if (depth <= 1) continue
      found.push(...cacheFiles({ root: absolute, depth: depth - 1 }))
      continue
    }
    if (entry.isFile() && entry.name === CACHE_FILE) found.push(absolute)
  }
  return found
}

/**
 * Follow the artifact headers under the output root.
 * @param {object} input - the walk input.
 * @param {string} input.root - absolute output root.
 * @param {string} input.cwd - working directory.
 * @param {number} input.depth - remaining depth.
 * @param {object[]} input.records - the accumulator.
 * @returns {void}
 */
function walkOutputs({ root, cwd, depth, records }) {
  for (const entry of readEntries(root)) {
    const absolute = join(root, entry.name)
    if (entry.isDirectory()) {
      // A cache directory is xl's own history, not a product: it is read by
      // `walkCaches` and never reported as residue of its own.
      if (entry.name === '.xl' || depth <= 1) continue
      walkOutputs({ root: absolute, cwd, depth: depth - 1, records })
      continue
    }
    if (!entry.isFile()) continue
    const head = readHead(absolute)
    if (!head.includes(HEADER_MARK)) continue
    const header = parseArtifactHeader(head)
    if (header === null) continue
    if (sourceExists(cwd, header.sourcePath)) continue
    records.push({
      out: displayPath(cwd, absolute),
      source: header.sourcePath,
      target: header.target === '' ? null : header.target,
      found: 'header',
      exists: true,
      reason: `"${displayPath(cwd, absolute)}" was generated from "${header.sourcePath}", which no longer exists`,
    })
  }
}

/**
 * Follow the per-language cache documents under the output root.
 *
 * The cache is found by shape, not by the configured language list: a language
 * that was dropped from `xl.json` still has its cache on disk, and its products
 * are exactly the ones nobody plans any more.
 * @param {object} input - the walk input.
 * @param {string} input.root - absolute output root.
 * @param {string} input.cwd - working directory.
 * @param {number} input.depth - remaining depth.
 * @param {object[]} input.records - the accumulator.
 * @returns {void}
 */
function walkCaches({ root, cwd, depth, records }) {
  for (const file of cacheFiles({ root, depth })) {
    for (const record of cacheOrphans(cwd, file)) records.push(record)
  }
}

/**
 * The residue one cache document records: entries whose source is gone.
 *
 * A cache entry is only believed when it names at least one product path, which
 * is what keeps an unrelated `cache.json` (a build tool's own) from being read
 * as xl state.
 * @param {string} cwd - working directory.
 * @param {string} file - absolute path of the cache document.
 * @returns {object[]} the records it contributes.
 */
function cacheOrphans(cwd, file) {
  let parsed
  try {
    parsed = JSON.parse(readFileSync(file, 'utf8'))
  } catch {
    return []
  }
  const entries = parsed?.entries
  if (entries === null || typeof entries !== 'object') return []
  const records = []
  for (const [key, value] of Object.entries(entries)) {
    const separator = key.indexOf(KEY_SEPARATOR)
    if (separator <= 0) continue
    const src = key.slice(0, separator)
    const target = key.slice(separator + 1)
    if (sourceExists(cwd, src)) continue
    const outputs = Array.isArray(value?.out) ? value.out.filter(path => typeof path === 'string') : []
    if (outputs.length === 0) continue
    for (const out of outputs) {
      const absolute = resolveOutput(cwd, out)
      const display = displayPath(cwd, absolute)
      const exists = statOf(absolute)?.isFile() === true
      records.push({
        out: display,
        source: src,
        target: target === '' ? null : target,
        found: 'cache',
        exists,
        reason: exists
          ? `"${display}" was generated from "${src}", which no longer exists`
          : `the cache still lists "${display}" as the current product of "${src}", which no longer exists — both the source and the product are gone`,
      })
    }
  }
  return records
}

/**
 * Deduplicate the two channels into one stable report.
 *
 * The header channel knows the target by reading the product; the cache channel
 * knows a product that is no longer there. Where both saw the same path, the
 * header wins — it describes the file that is actually on disk.
 * @param {readonly object[]} records - everything both channels found.
 * @returns {Orphan[]} the merged report.
 */
function finalize(records) {
  /** @type {Map<string, object>} */
  const byPath = new Map()
  for (const record of records) {
    const existing = byPath.get(record.out)
    if (existing === undefined || (existing.found === 'cache' && record.found === 'header')) {
      byPath.set(record.out, record)
    }
  }
  return [...byPath.values()].sort((left, right) => compare(left.out, right.out))
}

/**
 * The repair hint of one residue record: what the reader can do about it.
 * @param {Orphan} orphan - the record.
 * @returns {string} the hint.
 */
function helpOf(orphan) {
  if (!orphan.exists) {
    return '产物已经不在盘上，只是 cache 还记着它；`xl orphans --prune` 会同时丢掉这条记录，或恢复源文件后重新生成'
  }
  return `确认这次删除后跑 \`xl orphans --prune\` 删掉残留产物，或恢复 ${orphan.source ?? '源文件'} 后重新生成`
}

/**
 * Whether a recorded source path still exists.
 *
 * Paths in a header and a cache are recorded the way the invocation named them
 * (POSIX, relative to the invocation's working directory); a run from a
 * different directory is why the path is also tried against the process's own
 * working directory.
 * @param {string} cwd - working directory.
 * @param {string} source - the recorded source path.
 * @returns {boolean} whether the source is still there.
 */
function sourceExists(cwd, source) {
  if (typeof source !== 'string' || source.trim() === '') return true
  const candidates = isAbsolute(source) ? [source] : [resolve(cwd, source), resolve(source)]
  return candidates.some(candidate => statOf(candidate) !== null)
}

/**
 * A path as the caller names paths: POSIX, relative to the working directory
 * when it lives under it, absolute otherwise.
 * @param {string} cwd - working directory.
 * @param {string} absolute - the absolute path.
 * @returns {string} the display path.
 */
function displayPath(cwd, absolute) {
  const posix = toPosix(absolute)
  const prefix = toPosix(resolve(cwd))
  if (posix === prefix) return '.'
  return posix.startsWith(`${prefix}/`) ? posix.slice(prefix.length + 1) : posix
}

/**
 * Read a directory, tolerating one that cannot be listed.
 * @param {string} directory - absolute directory.
 * @returns {import('node:fs').Dirent[]} the entries, or none.
 */
function readEntries(directory) {
  try {
    return readdirSync(directory, { withFileTypes: true })
  } catch {
    return []
  }
}

/**
 * The first bytes of a file, decoded. A header lives in the first three lines,
 * so a product of any size costs one bounded read.
 * @param {string} file - absolute file path.
 * @returns {string} the decoded head, or the empty string.
 */
function readHead(file) {
  let bytes
  try {
    bytes = readFileSync(file)
  } catch {
    return ''
  }
  return bytes.subarray(0, HEAD_BYTES).toString('utf8')
}

/**
 * Whether a file currently starts with an xl header. This is the proof
 * {@link removeOrphans} demands before it deletes anything.
 * @param {string} file - absolute file path.
 * @returns {boolean} whether xl wrote it.
 */
function isArtifactFile(file) {
  const head = readHead(file)
  if (!head.includes(HEADER_MARK)) return false
  return parseArtifactHeader(head) !== null
}

/**
 * `statSync` without the throw, or `null` when the path is not there.
 * @param {string} path - absolute path.
 * @returns {import('node:fs').Stats | null} the stats, or `null`.
 */
function statOf(path) {
  try {
    return statSync(path)
  } catch {
    return null
  }
}

/**
 * Code-unit comparison, so ordering never depends on the host's collation.
 * @param {string} left - first text.
 * @param {string} right - second text.
 * @returns {number} negative, zero, or positive.
 */
function compare(left, right) {
  if (left === right) return 0
  return left < right ? -1 : 1
}
